import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import {readFile} from 'node:fs/promises';
import {PlatformStore} from '../server/platform.js';
import {normalizeConfig} from '../server/config.js';
import {platformHost} from './helpers/platform-host.js';

// End to end over a real host: an organiser creates a link, a captain opens it without an account,
// submits, the organiser approves and applies, and the roster lands in the tournament. Everything the
// browser does is an ordinary fetch against the routes the panel and the portal page use.
const TOKEN='platform-route-test-panel-token';
const config=()=>normalizeConfig({
 event:{name:'Autumn Cup'},format:'bo1',
 maps:[{name:'de_mirage'}],
 teams:[{id:'t1',name:'Nova',tag:'NOV'},{id:'t2',name:'Falcons',tag:'FLC'}],
});

test('a captain submits a roster through a signed link and the organiser applies it',async t=>{
 const host=await platformHost(t,{},async directory=>{
  const store=await new PlatformStore(path.join(directory,'config','platform','store.json')).load();
  const created=await store.create('acct_1','owner@example.com','Autumn Cup',config());
  if(!created.ok) throw Error(created.message);
  await store.setPublication(created.value.id,'acct_1',{published:true,visibility:'unlisted',slug:'autumn-cup'});
 });
 const organizer={headers:{'x-scout-token':TOKEN}} as const;
 const created=await host.request('/api/portal/links',{teamId:'t1',eventId:'__EVENT__'},{...organizer,method:'POST'});
 // The event id is generated by the store; read it from the platform file the host already loaded.
 const store=JSON.parse(await readFile(path.join(host.directory,'config','platform','store.json'),'utf8'));
 const eventId=store.tournaments[0].id as string;
 assert.equal(created.status,404,'a tournament id that does not exist is refused');
 const link=await host.request('/api/portal/links',{teamId:'t1',eventId},{...organizer,method:'POST'});
 assert.equal(link.status,201);
 assert.match(link.body.url,/^\/portal\/[A-Za-z0-9_-]{32}$/);
 const token=String(link.body.url).split('/').pop()!;

 const context=await host.request(`/api/public/portal/${token}`);
 assert.equal(context.status,200);
 assert.equal(context.body.status,'active');
 assert.equal(context.body.team.name,'Nova');
 assert.equal(context.body.team.players.length,0);

 const submitted=await host.request(`/api/public/portal/${token}`,{teamName:'Nova Esports',tag:'NOV',logo:'',socials:{x:'@nova',twitch:'',website:'',discord:''},players:[{nickname:'s1mple',role:'AWPer',steamid:''},{nickname:'b1t',role:'Rifler',steamid:''}],note:'please'});
 assert.equal(submitted.status,201);

 const queue=await host.request('/api/portal/links',undefined,organizer);
 assert.equal(queue.body.queue.length,1);
 assert.equal(queue.body.queue[0].payload.teamName,'Nova Esports');
 const linkId=queue.body.queue[0].linkId as string;
 const submissionId=queue.body.queue[0].submissionId as string;

 const approved=await host.request(`/api/portal/links/${linkId}/submissions/${submissionId}/approve`,{},{...organizer,method:'POST'});
 assert.equal(approved.status,200);
 assert.equal(approved.body.submission.status,'approved');

 const applied=await host.request(`/api/portal/links/${linkId}/submissions/${submissionId}/apply`,{},{...organizer,method:'POST'});
 assert.equal(applied.status,200);
 assert.equal(applied.body.applied.players,2);

 const after=JSON.parse(await readFile(path.join(host.directory,'config','platform','store.json'),'utf8'));
 const team=after.tournaments[0].config.teams.find((candidate:any)=>candidate.id==='t1');
 assert.equal(team.name,'Nova Esports');
 assert.deepEqual(team.players.map((player:any)=>player.nickname),['s1mple','b1t']);
});

test('an expired or revoked link cannot submit, and the public page says so',async t=>{
 const host=await platformHost(t,{},async directory=>{
  const store=await new PlatformStore(path.join(directory,'config','platform','store.json')).load();
  const created=await store.create('acct_1','owner@example.com','Autumn Cup',config());
  if(!created.ok) throw Error(created.message);
 });
 const organizer={headers:{'x-scout-token':TOKEN}} as const;
 const store=JSON.parse(await readFile(path.join(host.directory,'config','platform','store.json'),'utf8'));
 const eventId=store.tournaments[0].id as string;
 const link=await host.request('/api/portal/links',{teamId:'t1',eventId},{...organizer,method:'POST'});
 const token=String(link.body.url).split('/').pop()!;
 const revoked=await host.request(`/api/portal/links/${link.body.link.id}`,undefined,{...organizer,method:'DELETE'});
 assert.equal(revoked.status,200);
 const context=await host.request(`/api/public/portal/${token}`);
 assert.equal(context.status,200);
 assert.equal(context.body.status,'revoked');
 const refused=await host.request(`/api/public/portal/${token}`,{teamName:'Nova',players:[{nickname:'x'}]});
 assert.equal(refused.status,410);
 assert.equal(refused.body.code,'revoked');
});
